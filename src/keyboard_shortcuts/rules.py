from dataclasses import dataclass
import ntpath
import re

MODIFIERS = tuple(side for family in ("Shift", "Control", "Alt", "Meta")
                  for side in (family + "Left", family + "Right"))
KEYS = MODIFIERS + tuple("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789") + (
    "ArrowLeft", "ArrowUp", "ArrowDown", "ArrowRight", "Home", "End", "PageUp",
    "PageDown", "Insert", "Delete", "Backspace", "Enter", "Escape", "Tab",
    "Space", "CapsLock", "PrintScreen", "ScrollLock", "Pause", "NumLock",
    "Minus", "Equal", "BracketLeft", "BracketRight", "Backslash", "Semicolon",
    "Quote", "Backquote", "Comma", "Period", "Slash", "ContextMenu",
) + tuple(f"F{i}" for i in range(1, 25)) + tuple(f"Numpad{i}" for i in range(10)) + (
    "NumpadAdd", "NumpadSubtract", "NumpadMultiply", "NumpadDivide",
    "NumpadDecimal", "NumpadEnter", "IntlBackslash",
)
LABELS = dict(zip(MODIFIERS, ("左 Shift", "右 Shift", "左 Ctrl", "右 Ctrl",
                             "左 Alt", "右 Alt", "左 Win", "右 Win")))
LABELS.update({f"Arrow{key}": key for key in ("Left", "Up", "Down", "Right")})


def label(key: str) -> str:
    return LABELS.get(key, key)


def canonical(keys: tuple[str, ...]) -> tuple[str, ...]:
    if not keys or len(keys) > 8 or len(set(keys)) != len(keys) or not set(keys) <= set(KEYS):
        raise ValueError("请选择 1–8 个不同的受支持按键。")
    return tuple(key for key in MODIFIERS if key in keys) + tuple(
        key for key in keys if key not in MODIFIERS
    )


@dataclass(frozen=True)
class Rule:
    source: tuple[str, ...]
    target: tuple[str, ...]
    app_path: str | None = None
    enabled: bool = True

    def __post_init__(self):
        object.__setattr__(self, "source", canonical(self.source))
        object.__setattr__(self, "target", canonical(self.target))
        if self.app_path is not None:
            path = ntpath.normpath(self.app_path)
            if not ntpath.isabs(path) or not path.lower().endswith(".exe") or any(
                ord(c) < 32 or c in '"/' for c in path
            ):
                raise ValueError("请选择有效的程序文件（.exe）。")
            object.__setattr__(self, "app_path", path)
        if type(self.enabled) is not bool:
            raise ValueError("规则启用状态无效。")


def default_rules() -> list[Rule]:
    return [Rule(("ShiftLeft", key), (f"Arrow{direction}",))
            for key, direction in zip("DFJK", ("Left", "Up", "Down", "Right"))]


def rule_key(rule: Rule):
    return frozenset(rule.source), (rule.app_path or "").casefold()


def find_conflict(candidate: Rule, rules: list[Rule]) -> int | None:
    return next((i for i, rule in enumerate(rules) if rule_key(rule) == rule_key(candidate)), None)


def expression(keys: tuple[str, ...]) -> str:
    return keys[0] if len(keys) == 1 else "(" + " ".join(keys) + ")"


def input_expression(keys: tuple[str, ...]) -> str:
    modifiers = tuple(key for key in keys if key in MODIFIERS)
    ordinary = tuple(key for key in keys if key not in MODIFIERS)
    if modifiers and ordinary:
        return f"{expression(modifiers)}{{{expression(ordinary)}}}"
    return expression(keys)


def compile_config(rules: list[Rule]) -> str:
    lines = ["# Generated by Keyboard Manager"]
    active = [rule for rule in rules if rule.enabled]
    active.sort(key=lambda rule: (rule.app_path is None, -len(rule.source)))
    for rule in active:
        lines.append(f"[path=/^{re.escape(rule.app_path)}$/i]" if rule.app_path else "[default]")
        exclusions = " ".join("!" + key for key in KEYS if key not in rule.source)
        output = expression(rule.target)
        lines.append(f"{exclusions} {input_expression(rule.source)} >> !Any {output}")
    return "\n".join(lines) + "\n"

